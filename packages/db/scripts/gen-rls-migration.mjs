// Generates the RLS migration from schema.prisma so no tenant table can be forgotten.
// Run: node scripts/gen-rls-migration.mjs   (writes prisma/migrations/20261010000002_rls/migration.sql)
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schema = readFileSync(resolve(here, "../prisma/schema.prisma"), "utf8");

// Models that carry a tenantId column
const tenantTables = [];
const allModels = [];
for (const m of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  allModels.push(m[1]);
  // required tenantId only; a nullable one (PlatformAuditLog) is platform-level
  if (/^\s+tenantId\s+String(?!\?)/m.test(m[2])) tenantTables.push(m[1]);
}
// Platform-level tables: no tenantId, no tenant access (see docs/08 section 3.4)
const platformTables = ["Plan", "Announcement", "PlatformUser", "PlatformAuditLog", "PlatformDailyMetrics", "PhoneTrustStat"];
const appReadable = ["Plan", "Announcement"]; // SELECT only for the tenant app role

// Same-tenant parent checks: [childTable, fkColumn, parentTable]
const fkChecks = [
  ["OrderItem", "productId", "Product"], ["OrderItem", "variantId", "ProductVariant"], ["OrderItem", "orderId", "Order"],
  ["Order", "customerId", "Customer"], ["OrderStateLog", "orderId", "Order"], ["RefundLedger", "orderId", "Order"],
  ["ProductVariant", "productId", "Product"], ["ProductImage", "productId", "Product"],
  ["Review", "productId", "Product"], ["Review", "customerId", "Customer"], ["ReturnRequest", "orderId", "Order"],
  ["CustomerAddress", "customerId", "Customer"], ["CollectionProduct", "productId", "Product"], ["CollectionProduct", "collectionId", "Collection"],
  ["TicketMessage", "ticketId", "SupportTicket"], ["CourierSettledOrder", "orderId", "Order"], ["CourierSettledOrder", "settlementId", "CourierSettlementInvoice"],
  ["LoyaltyTransaction", "accountId", "CustomerLoyaltyAccount"],
].filter(([c, col, p]) => allModels.includes(c) && allModels.includes(p) && new RegExp(`^model ${c} \\{[\\s\\S]*?^\\s+${col}\\s`, "m").test(schema));

const q = (t) => `"${t}"`;
let sql = `-- Row-level security, generated by packages/db/scripts/gen-rls-migration.mjs. Do not edit by hand.
-- Source of truth: docs/08-database-schema-and-rls-spec.md section 3.

-- Roles are created without a password here. Set login passwords with scripts/db-roles.sql (kept out of git).
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'biztrack_app') THEN
    CREATE ROLE biztrack_app NOLOGIN NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'biztrack_platform') THEN
    CREATE ROLE biztrack_platform NOLOGIN BYPASSRLS;
  END IF;
END $$;

GRANT USAGE ON SCHEMA public TO biztrack_app, biztrack_platform;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO biztrack_platform;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO biztrack_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO biztrack_platform;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO biztrack_app;

-- Platform-level tables are invisible to the tenant app role, except Plan and Announcement (read only)
${platformTables.map((t) => `REVOKE ALL ON ${q(t)} FROM biztrack_app;`).join("\n")}
${appReadable.map((t) => `GRANT SELECT ON ${q(t)} TO biztrack_app;`).join("\n")}

-- Current tenant from the transaction-local setting. Empty string means no tenant: policies then match nothing.
CREATE OR REPLACE FUNCTION current_tenant() RETURNS text AS $$
  SELECT NULLIF(current_setting('app.current_tenant_id', true), '');
$$ LANGUAGE sql STABLE;

-- ---- Tenant isolation on every table with a tenantId (${tenantTables.length} tables)
DO $$
DECLARE tbl text;
  tenant_tables text[] := ARRAY[${tenantTables.map((t) => `'${t}'`).join(", ")}];
BEGIN
  FOREACH tbl IN ARRAY tenant_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_policy ON %I', tbl);
    EXECUTE format('CREATE POLICY tenant_isolation_policy ON %I FOR ALL TO biztrack_app USING ("tenantId" = current_tenant()) WITH CHECK ("tenantId" = current_tenant())', tbl);
  END LOOP;
END $$;

-- ---- The Tenant row itself: an app connection can only see and update its own tenant
ALTER TABLE "Tenant" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Tenant" FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_self_policy ON "Tenant";
CREATE POLICY tenant_self_policy ON "Tenant" FOR ALL TO biztrack_app USING (id = current_tenant()) WITH CHECK (id = current_tenant());

-- ---- Hostname to tenant lookup for the edge and storefront. SECURITY DEFINER so it works before a tenant is known.
-- Returns at most one row and only non-sensitive columns.
CREATE OR REPLACE FUNCTION resolve_tenant_by_host(p_host text, p_root_domain text)
RETURNS TABLE (id text, status "TenantStatus", "themeId" text, subdomain text, locale text) AS $$
  SELECT t.id, t.status, t."themeId", t.subdomain, t.locale
  FROM "Tenant" t
  WHERE (p_host LIKE '%.' || p_root_domain AND t.subdomain = split_part(p_host, '.', 1))
     OR EXISTS (SELECT 1 FROM "Domain" d WHERE d."tenantId" = t.id AND d.domain = p_host AND d.verified)
  LIMIT 1;
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public;
REVOKE ALL ON FUNCTION resolve_tenant_by_host(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION resolve_tenant_by_host(text, text) TO biztrack_app, biztrack_platform;

-- ---- Cross-tenant foreign key guard: a child row may only point at a parent of the same tenant
CREATE OR REPLACE FUNCTION assert_same_tenant() RETURNS trigger AS $$
DECLARE
  parent_table text := TG_ARGV[0];
  fk_column text := TG_ARGV[1];
  fk_value text;
  ok boolean;
BEGIN
  EXECUTE format('SELECT ($1).%I::text', fk_column) INTO fk_value USING NEW;
  IF fk_value IS NULL THEN RETURN NEW; END IF;
  EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I WHERE id = $1 AND "tenantId" = $2)', parent_table) INTO ok USING fk_value, NEW."tenantId";
  IF NOT ok THEN
    RAISE EXCEPTION 'Cross-tenant reference blocked: %.% = % is not in tenant %', TG_TABLE_NAME, fk_column, fk_value, NEW."tenantId" USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;
${fkChecks.map(([c, col, p]) => `DROP TRIGGER IF EXISTS trg_tenant_fk_${c}_${col} ON ${q(c)};\nCREATE TRIGGER trg_tenant_fk_${c}_${col} BEFORE INSERT OR UPDATE ON ${q(c)} FOR EACH ROW EXECUTE FUNCTION assert_same_tenant('${p}', '${col}');`).join("\n")}
`;

const dir = resolve(here, "../prisma/migrations/20261010000002_rls");
mkdirSync(dir, { recursive: true });
writeFileSync(resolve(dir, "migration.sql"), sql);
console.log(`RLS migration written: ${tenantTables.length} tenant tables, ${fkChecks.length} cross-tenant FK guards`);
console.log("Tenant tables:", tenantTables.join(", "));
