// Writes one ready-to-paste environment file per Vercel project into deploy-env/ (gitignored), from the values already in .env.local
// plus newly generated secrets. The generated secrets are kept in .env.production.local (also gitignored) so running this again
// reuses them: never regenerate PHONE_TRUST_SALT or INTEGRATION_VAULT_SECRET once real data exists.
//   node tools/make-vercel-env.mjs [--domain biztrack.bd]
// In each Vercel project: Settings, Environment Variables, click into the first "Key" box and paste the whole file: Vercel splits it.
// Lines left empty (marked TODO) are values only you can supply. Review the printed "check" list before pasting.
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const domain = args.includes("--domain") ? args[args.indexOf("--domain") + 1] : "biztrack.bd";

const parse = (file) => {
  const out = {};
  if (!existsSync(file)) return out;
  for (const l of readFileSync(file, "utf8").replace(/\r/g, "").split("\n")) {
    const m = l.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
    if (m) out[m[1]] = m[2].replace(/^"|"$/g, "");
  }
  return out;
};
const local = parse(join(root, ".env.local"));
const genFile = join(root, ".env.production.local");
const gen = parse(genFile);
const hex = (n) => randomBytes(n).toString("hex");
let created = [];
for (const [k, make] of Object.entries({
  CUSTOMER_AUTH_SECRET: () => hex(32),
  INTEGRATION_VAULT_SECRET: () => hex(32), // 64 hex characters
  PREVIEW_SECRET: () => hex(24),
  PHONE_TRUST_SALT: () => hex(24),
  CRON_SECRET: () => hex(24),
  BACKUP_ENCRYPTION_KEY_HEX: () => hex(32),
})) {
  if (!gen[k]) { gen[k] = make(); created.push(k); }
}
if (created.length) {
  writeFileSync(genFile, "# Generated by tools/make-vercel-env.mjs. KEEP A COPY IN A PASSWORD MANAGER. Never commit.\n" + Object.entries(gen).map(([k, v]) => `${k}="${v}"`).join("\n") + "\n");
  console.log(`generated: ${created.join(", ")}  (saved in .env.production.local)`);
}

const L = (k, v, note) => `${k}="${v ?? ""}"${note ? `  # ${note}` : ""}`;
// A TODO line is filled from .env.local when you have added the value there (BREVO_API_KEY, SMS_SENDER_ID, PLATFORM_VERCEL_TOKEN, PLATFORM_VERCEL_PROJECT_ID, EDGE_CONFIG_ID, EDGE_CONFIG ...).
const todo = (k, note) => (local[k] ? `${k}="${local[k]}"` : `${k}=""  # TODO: ${note}`);
const need = (k) => { if (!local[k]) console.log(`  missing in .env.local: ${k}`); return local[k]; };
const site = `https://${domain}`, admin = `https://admin.${domain}`, platform = `https://platform.${domain}`;

const common = [
  L("DATABASE_URL", need("SUPABASE_APP_DB_URL"), "the biztrack_app login (restricted), session pooler"),
  L("DB_POOL_MAX", "1"),
  L("NEXT_PUBLIC_ROOT_DOMAIN", domain),
];
const supabase = [
  L("SUPABASE_URL", need("SUPABASE_URL")),
  L("NEXT_PUBLIC_SUPABASE_URL", need("NEXT_PUBLIC_SUPABASE_URL")),
  L("SUPABASE_PUBLISHABLE_KEY", need("SUPABASE_PUBLISHABLE_KEY")),
  L("NEXT_PUBLIC_SUPABASE_ANON_KEY", need("NEXT_PUBLIC_SUPABASE_ANON_KEY")),
  L("SUPABASE_SERVICE_ROLE_KEY", need("SUPABASE_SERVICE_ROLE_KEY"), "server only; never expose"),
];
const sms = [
  L("SMS_PROVIDER", "smsnetbd"),
  L("SMS_NET_BD_API_KEY", local.SMS_NET_BD_API_KEY, "rotate it: it was pasted into a chat"),
  todo("SMS_SENDER_ID", "optional: your approved sender id"),
];
const email = [todo("BREVO_API_KEY", "from Brevo: SMTP & API, API keys (make one named biztrack-production)"), L("EMAIL_FROM", `no-reply@${domain}`), L("EMAIL_FROM_NAME", "BizTrackBD")];
const payments = [
  // Production numbers live in .env.production.local (never the test numbers in .env.local).
  L("PLATFORM_BKASH_NUMBER", gen.PLATFORM_BKASH_NUMBER ?? local.PLATFORM_BKASH_NUMBER, "the bKash number stores pay subscriptions to"),
  L("PLATFORM_BKASH_KIND", gen.PLATFORM_BKASH_KIND ?? "MERCHANT", "MERCHANT or PERSONAL"),
  L("PLATFORM_NAGAD_NUMBER", gen.PLATFORM_NAGAD_NUMBER ?? local.PLATFORM_NAGAD_NUMBER, "the Nagad number"),
  L("PLATFORM_NAGAD_KIND", gen.PLATFORM_NAGAD_KIND ?? "MERCHANT", "MERCHANT or PERSONAL"),
];
const shared = (...ks) => ks.map((k) => L(k, gen[k]));

const files = {
  // Signup draws pictures for the sample products (docs/38), so marketing needs the picture storage settings too. The template demo links are built from the root domain.
  marketing: [...common, L("NEXT_PUBLIC_MARKETING_URL", site), L("NEXT_PUBLIC_ADMIN_URL", admin), L("SUPABASE_URL", need("SUPABASE_URL")), L("SUPABASE_SERVICE_ROLE_KEY", need("SUPABASE_SERVICE_ROLE_KEY"), "server only; never expose"), L("MEDIA_DRIVER", "supabase"), L("MEDIA_BUCKET", "store-media")],
  admin: [
    ...common, ...supabase, ...shared("CRON_SECRET", "CUSTOMER_AUTH_SECRET", "INTEGRATION_VAULT_SECRET", "PREVIEW_SECRET", "PHONE_TRUST_SALT"),
    L("INTEGRATION_VAULT_KEY_ID", "v1"), L("ADMIN_ORIGIN", admin), L("NEXT_PUBLIC_ADMIN_URL", admin),
    L("MEDIA_DRIVER", "supabase"), L("MEDIA_BUCKET", "store-media"), ...payments,
    L("PLATFORM_A_RECORD", local.PLATFORM_A_RECORD || "76.76.21.21"), L("PLATFORM_CNAME_TARGET", `cname.${domain}`),
    todo("PLATFORM_VERCEL_TOKEN", "vercel.com, Account Settings, Tokens: lets the app add stores' custom domains and update routing (Vercel refuses variable names starting VERCEL_)"), todo("PLATFORM_VERCEL_PROJECT_ID", "the biztrack-storefront project's id"), todo("PLATFORM_VERCEL_TEAM_ID", "optional: only for a team-owned project"), todo("EDGE_CONFIG_ID", "Vercel Storage, Edge Config: the id (ecfg_...)"), todo("EDGE_CONFIG", "the Edge Config connection string"),
    ...sms, ...email,
  ],
  platform: [
    ...common, L("PLATFORM_DATABASE_URL", need("SUPABASE_PLATFORM_DB_URL"), "the biztrack_platform login"), ...supabase, ...shared("CRON_SECRET", "PHONE_TRUST_SALT"),
    ...payments,
    todo("PLATFORM_VERCEL_TOKEN", "same token as the admin project"), todo("PLATFORM_VERCEL_PROJECT_ID", "the storefront project's id"), todo("EDGE_CONFIG_ID", "same Edge Config id as the admin project"),
    ...sms, ...email,
  ],
  storefront: [
    ...common, ...shared("CUSTOMER_AUTH_SECRET", "INTEGRATION_VAULT_SECRET", "PREVIEW_SECRET", "PHONE_TRUST_SALT"), L("INTEGRATION_VAULT_KEY_ID", "v1"),
    L("NEXT_PUBLIC_ADMIN_URL", admin), L("NEXT_PUBLIC_SUPABASE_URL", need("NEXT_PUBLIC_SUPABASE_URL")), L("MEDIA_DRIVER", "supabase"), L("MEDIA_BUCKET", "store-media"),
    todo("EDGE_CONFIG", "the same Edge Config as the admin project"), ...sms,
  ],
};

mkdirSync(join(root, "deploy-env"), { recursive: true });
for (const [app, lines] of Object.entries(files)) {
  writeFileSync(join(root, "deploy-env", `${app}.env`), `# Vercel project biztrack-${app}. Generated by tools/make-vercel-env.mjs. Contains secrets: never commit, delete after pasting.\n${lines.join("\n")}\n`);
  const todos = lines.filter((l) => /# TODO/.test(l)).length;
  console.log(`wrote deploy-env/${app}.env  (${lines.length} variables, ${todos} left for you)`);
}
console.log("\ncheck before pasting: the two PLATFORM_*_NUMBER values must be the real wallet numbers; the SMS key should be rotated; every TODO line needs a value or removal.");
